// Merges the validated web-research batches (src/data/web/*.json) into per-letter shards the site
// loads on demand: src/data/webrec/<c>.json plus an index of loaders. Invalid batches are skipped and named.
//
//   node scripts/build-web.mjs
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { WebRecordSchema } from "../src/lib/product-schema.ts";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const dir = path.join(root, "src/data/web");
const out = path.join(root, "src/data/webrec");
fs.rmSync(out, { recursive: true, force: true });
fs.mkdirSync(out, { recursive: true });
fs.mkdirSync(dir, { recursive: true });

const shards = {};
let ok = 0, skipped = 0, found = 0;
for (const f of fs.readdirSync(dir).filter((x) => x.endsWith(".json")).sort()) {
  let data;
  try { data = JSON.parse(fs.readFileSync(path.join(dir, f), "utf8")); } catch { console.log(`skip ${f}: not JSON`); continue; }
  for (const rec of Array.isArray(data) ? data : []) {
    const r = WebRecordSchema.safeParse(rec);
    if (!r.success) { skipped++; continue; }
    const k = r.data.id[0].replace(/[^a-z0-9]/, "_");
    (shards[k] ??= {})[r.data.id.toLowerCase()] = r.data;
    ok++; if (r.data.found) found++;
  }
}
for (const [k, v] of Object.entries(shards)) fs.writeFileSync(path.join(out, k + ".json"), JSON.stringify(v));
fs.writeFileSync(path.join(out, "index.ts"),
  "// Generated by scripts/build-web.mjs. Do not edit.\n" +
  "export const webLoaders: Record<string, () => Promise<{ default: unknown }>> = {\n" +
  Object.keys(shards).sort().map((k) => `  ${JSON.stringify(k)}: () => import("./${k}.json"),`).join("\n") + "\n};\n");
console.log(`${ok} web records (${found} with sources), ${skipped} invalid skipped, ${Object.keys(shards).length} shards`);
