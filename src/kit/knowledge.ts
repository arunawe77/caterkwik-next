// The product page grounds Kit in PRODUCT_FACTS alone. The ovens pages add
// the category on top, generated by render.js from ovens.js, so he can never
// quote a price or a dimension those pages do not show.
export function systemPrompt(extra?: string): string {
  if (!extra) return SYSTEM_PROMPT;
  // Swap the product facts out, do not stack the category on top of them:
  // otherwise Kit keeps answering as though "this range" is the OTC/P when he
  // is on a page with thirty-two of them.
  return SYSTEM_PROMPT.includes(PRODUCT_FACTS)
    ? SYSTEM_PROMPT.replace(PRODUCT_FACTS, extra)
    : SYSTEM_PROMPT + '\n\n' + extra;
}
